import { test, expect } from "@playwright/test";
import { getDocument } from "pdfjs-dist/legacy/build/pdf.mjs";
import { learningExport } from "../fixtures/learning-ui.mjs";
import { importExportedConversation } from "../../src/lib/import/export-conversation.ts";
import { rasterPng } from "./fixtures.mjs";

test("lesson export includes opted-in illustrations, math, progress, quizzes and the diagram",async({page,context},testInfo)=>{
 await context.addInitScript(()=>{window.print=()=>{};});
 let requested=0;
 await context.route("https://lesson-assets.example/**",async route=>{
  requested++;
  await route.fulfill({contentType:"image/png",body:Buffer.from(rasterPng.split(",")[1],"base64")});
 });
 const {conversation,warnings}=importExportedConversation(learningExport());
 const url="https://chatgpt.com/share/6ae02482-696c-83ee-84bf-552ea26bacf0";
 await page.route("**/api/shared-link/inspect",route=>route.fulfill({json:{ok:true,canonicalUrl:url,conversionReady:true,retrieval:"complete",conversation,warnings,message:"Ready"}}));
 await page.goto("/#inspector");
 await page.locator("#shared-link").fill(url);
 await page.getByRole("button",{name:"Convert shared link to PDF"}).click();
 await expect(page.getByRole("button",{name:"Preview PDF with 5 online images"})).toBeVisible();
 expect(requested).toBe(0);
 await page.getByLabel("Page theme").selectOption("dark");
 const pending=page.waitForEvent("popup");
 await page.getByRole("button",{name:"Preview PDF with 5 online images"}).click();
 const popup=await pending;
 await expect(popup.getByRole("button",{name:"Print / Save as PDF",exact:true})).toBeEnabled();
 await expect(popup.locator(".media-block img")).toHaveCount(5);
 await expect(popup.locator(".media-block figcaption a")).toHaveCount(5);
 await expect(popup.locator(".math")).toHaveCount(5);
 await expect(popup.locator(".diagram-block svg")).toHaveCount(1);
 await expect(popup.locator(".visual-checkbox")).toHaveCount(5);
 await expect(popup.locator(".visual-radio")).toHaveCount(11);
 await expect(popup.locator(".visual-radio.is-checked")).toHaveCount(1);
 await expect(popup.locator(".visual-progress")).toHaveCount(1);
 expect(requested).toBe(5);
 expect(await popup.locator("img").evaluateAll(images=>images.every(img=>img.complete&&img.naturalWidth>0))).toBe(true);
 await expect(popup.locator(".export-document")).toContainText("Correct! A database stores data.");
 await expect(popup.locator(".export-document")).not.toContainText("FALLBACK_SHOULD_NOT_REPLACE_THE_LESSON");
 const statuses=await Promise.all(["200","404"].map(label=>popup.locator('.visual-layout[style*="grid"] p').filter({hasText:new RegExp(`^${label}$`)}).boundingBox()));
 expect(Math.abs(statuses[0].y-statuses[1].y)).toBeLessThan(3);
 expect(statuses[1].x).toBeGreaterThan(statuses[0].x+50);
 const bytes=await popup.pdf({path:testInfo.outputPath("lesson-fidelity.pdf"),preferCSSPageSize:true,printBackground:true});
 const task=getDocument({data:new Uint8Array(bytes),useSystemFonts:true});
 const pdf=await task.promise;
 let text="";
 for(let i=1;i<=pdf.numPages;i++)text+=(await (await pdf.getPage(i)).getTextContent()).items.map(item=>item.str).join(" ")+" ";
 expect(text).toContain("Correct! A database stores data.");
 expect(text).toContain("Client and server");
 expect(text).toContain("100");
 expect(text).not.toContain("flowchart TD");
 expect(text).not.toContain("\\text{");
 await task.destroy();
});
